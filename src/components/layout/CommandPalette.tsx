import React, { useState, useEffect } from 'react';
import { useNavigate } from 'react-router-dom';

interface CommandPaletteProps {
  isOpen: boolean;
  onClose: () => void;
}

export const CommandPalette: React.FC<CommandPaletteProps> = ({ isOpen, onClose }) => {
  const navigate = useNavigate();
  const [query, setQuery] = useState('');

  const commands = [
    { title: 'Overview Dashboard', subtitle: 'View primary academic trajectory & metric cards', path: '/dashboard', icon: 'dashboard', category: 'Navigation' },
    { title: 'Run New Prediction', subtitle: 'Open Computational Assessment Matrix calculator', path: '/predict', icon: 'auto_graph', category: 'Action' },
    { title: 'Prediction History Archive', subtitle: 'Audit trail of past runs and score trends', path: '/history', icon: 'history_edu', category: 'Navigation' },
    { title: 'Academic Analytics', subtitle: 'Deep dive Recharts progression & correlation charts', path: '/analytics', icon: 'insights', category: 'Navigation' },
    { title: 'Academic Recommendations', subtitle: 'Actionable study plan generated by Bayesian engine', path: '/recommendations', icon: 'psychology_alt', category: 'Action' },
    { title: 'Admin & Faculty Portal', subtitle: 'Cohort distribution & at-risk student monitoring', path: '/admin', icon: 'supervisor_account', category: 'Admin' },
    { title: 'Profile & Settings', subtitle: 'Configure target CGPA & backend endpoints', path: '/settings', icon: 'settings', category: 'Settings' },
    { title: 'Module: CS601 Python Programming', subtitle: '4 Credits • Lead Instructor: Dr. Rao (88% Distinction)', path: '/analytics', icon: 'code', category: 'Module' },
    { title: 'Module: CS602 Database Management', subtitle: '4 Credits • Lead Instructor: Prof. Mehta (84% Strong)', path: '/analytics', icon: 'database', category: 'Module' },
    { title: 'Module: MA601 Engineering Mathematics IV', subtitle: '4 Credits • Numerical Methods focus area', path: '/predict', icon: 'calculate', category: 'Module' },
  ];

  const filtered = commands.filter(item =>
    item.title.toLowerCase().includes(query.toLowerCase()) ||
    item.subtitle.toLowerCase().includes(query.toLowerCase()) ||
    item.category.toLowerCase().includes(query.toLowerCase())
  );

  useEffect(() => {
    const handleKeyDown = (e: KeyboardEvent) => {
      if ((e.ctrlKey || e.metaKey) && e.key === 'k') {
        e.preventDefault();
        if (isOpen) onClose();
        else onClose(); // parent handles toggle
      }
      if (e.key === 'Escape' && isOpen) {
        onClose();
      }
    };
    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, [isOpen, onClose]);

  if (!isOpen) return null;

  return (
    <div className="fixed inset-0 z-50 flex items-start justify-center pt-20 px-4 bg-slate-900/40 backdrop-blur-xs animate-in fade-in duration-100">
      <div className="relative w-full max-w-xl bg-white rounded-2xl shadow-2xl border border-slate-200 overflow-hidden flex flex-col">
        {/* Search Input */}
        <div className="flex items-center px-4 border-b border-slate-100">
          <span className="material-symbols-outlined text-slate-400 text-[20px] mr-3">search</span>
          <input
            type="text"
            placeholder="Type a command, module name, or navigation path..."
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            autoFocus
            className="w-full py-4 text-sm text-slate-800 placeholder-slate-400 bg-transparent outline-none"
          />
          <button
            onClick={onClose}
            className="p-1 rounded-md text-slate-400 hover:text-slate-600 hover:bg-slate-100 text-xs font-semibold px-2"
          >
            ESC
          </button>
        </div>

        {/* Command List */}
        <div className="max-h-80 overflow-y-auto p-2 flex flex-col gap-1">
          {filtered.length === 0 ? (
            <div className="p-6 text-center text-xs text-slate-400">
              No matching modules or actions found for "{query}".
            </div>
          ) : (
            filtered.map((item, idx) => (
              <button
                key={idx}
                onClick={() => {
                  navigate(item.path);
                  onClose();
                }}
                className="w-full flex items-center justify-between p-2.5 rounded-xl hover:bg-slate-50 transition-colors text-left group"
              >
                <div className="flex items-center gap-3 min-w-0">
                  <div className="w-8 h-8 rounded-lg bg-slate-100 text-slate-600 group-hover:bg-indigo-50 group-hover:text-indigo-600 flex items-center justify-center shrink-0 transition-colors">
                    <span className="material-symbols-outlined text-[18px]">{item.icon}</span>
                  </div>
                  <div className="flex flex-col min-w-0">
                    <span className="text-xs font-bold text-slate-800 group-hover:text-indigo-600 transition-colors truncate">
                      {item.title}
                    </span>
                    <span className="text-[11px] text-slate-400 truncate">{item.subtitle}</span>
                  </div>
                </div>
                <span className="text-[10px] font-semibold text-slate-400 uppercase tracking-wider bg-slate-100 px-2 py-0.5 rounded shrink-0">
                  {item.category}
                </span>
              </button>
            ))
          )}
        </div>

        {/* Footer */}
        <div className="p-2.5 bg-slate-50 border-t border-slate-100 text-[11px] text-slate-400 flex items-center justify-between px-4">
          <span>Navigate with arrows or click to select</span>
          <span className="font-semibold text-slate-500">StudentAI Quick Command</span>
        </div>
      </div>
    </div>
  );
};
