import React, { useState } from 'react';
import { Link } from 'react-router-dom';
import { getStoredRecommendations, toggleStoredRecommendation } from '../data/mockData';

export const RecommendationsPage: React.FC = () => {
  const [recommendations, setRecommendations] = useState(getStoredRecommendations);
  const [activeFilter, setActiveFilter] = useState<'all' | 'high' | 'medium' | 'routine'>('all');
  const [selectedModule, setSelectedModule] = useState<string>('all');
  const [studyPlanHours, setStudyPlanHours] = useState<number>(4);
  const [generatedPlan, setGeneratedPlan] = useState<boolean>(false);

  const completedCount = recommendations.filter(r => r.completed).length;
  const progressPct = Math.round((completedCount / recommendations.length) * 100);

  const handleToggle = (id: string) => {
    const updated = toggleStoredRecommendation(id);
    setRecommendations(updated);
  };

  const filtered = recommendations.filter(item => {
    const matchesPriority = activeFilter === 'all' || item.priority === activeFilter;
    const matchesModule = selectedModule === 'all' || item.moduleRelated.toLowerCase().includes(selectedModule.toLowerCase());
    return matchesPriority && matchesModule;
  });

  return (
    <div className="flex flex-col w-full pb-16">
      <div className="px-4 md:px-6 py-6 flex flex-col gap-6 max-w-7xl mx-auto w-full">
        
        {/* Header */}
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
          <div className="flex flex-col gap-1">
            <nav className="flex items-center gap-2 text-xs text-slate-500">
              <Link to="/dashboard" className="hover:text-slate-900 transition-colors font-medium">Overview</Link>
              <span className="material-symbols-outlined text-[16px] text-slate-400">chevron_right</span>
              <span className="text-slate-900 font-semibold">Academic Recommendations</span>
            </nav>
            <h1 className="text-2xl sm:text-3xl font-extrabold text-slate-900 tracking-tight">
              Personalized Academic Recommendations
            </h1>
            <p className="text-xs text-slate-500">
              Targeted study interventions and coursework remediation levers generated by the Bayesian diagnostic engine
            </p>
          </div>

          <div className="px-4 py-2.5 rounded-xl bg-white border border-slate-200 shadow-2xs flex items-center gap-3">
            <div className="flex flex-col items-end">
              <span className="text-xs font-bold text-slate-800">
                {completedCount} of {recommendations.length} Completed
              </span>
              <span className="text-[10px] text-slate-400">{progressPct}% Execution Rate</span>
            </div>
            <div className="w-16 bg-slate-100 rounded-full h-2 overflow-hidden">
              <div className="bg-indigo-600 h-2 rounded-full transition-all duration-300" style={{ width: `${progressPct}%` }}></div>
            </div>
          </div>
        </div>

        {/* Filter Toolbar */}
        <div className="bg-white rounded-xl p-4 border border-slate-200 shadow-xs flex flex-wrap items-center justify-between gap-3">
          {/* Priority Tabs */}
          <div className="flex items-center gap-1 bg-slate-100 p-1 rounded-lg border border-slate-200">
            <button
              onClick={() => setActiveFilter('all')}
              className={`px-3 py-1.5 rounded text-xs font-semibold transition-all ${
                activeFilter === 'all' ? 'bg-white text-slate-900 shadow-2xs' : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              All Priorities ({recommendations.length})
            </button>
            <button
              onClick={() => setActiveFilter('high')}
              className={`px-3 py-1.5 rounded text-xs font-semibold transition-all ${
                activeFilter === 'high' ? 'bg-white text-rose-700 shadow-2xs' : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              High Priority (2)
            </button>
            <button
              onClick={() => setActiveFilter('medium')}
              className={`px-3 py-1.5 rounded text-xs font-semibold transition-all ${
                activeFilter === 'medium' ? 'bg-white text-amber-700 shadow-2xs' : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              Medium Priority (2)
            </button>
            <button
              onClick={() => setActiveFilter('routine')}
              className={`px-3 py-1.5 rounded text-xs font-semibold transition-all ${
                activeFilter === 'routine' ? 'bg-white text-slate-900 shadow-2xs' : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              Routine Habits (3)
            </button>
          </div>

          {/* Module Selector */}
          <div className="flex items-center gap-2">
            <span className="text-xs text-slate-500 font-medium">Module:</span>
            <select
              value={selectedModule}
              onChange={(e) => setSelectedModule(e.target.value)}
              className="h-9 px-3 text-xs bg-slate-50 border border-slate-200 rounded-lg text-slate-700 font-semibold focus:outline-none focus:border-indigo-600 cursor-pointer"
            >
              <option value="all">All Modules</option>
              <option value="Mathematics IV">Mathematics IV</option>
              <option value="DBMS">Database Management</option>
              <option value="Computer Networks">Computer Networks</option>
              <option value="Python">Python Programming</option>
              <option value="General">Study Cadence</option>
            </select>
          </div>
        </div>

        {/* Recommendations List */}
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          {filtered.map((item) => (
            <div
              key={item.id}
              className={`bg-white rounded-2xl p-5 border transition-all flex flex-col justify-between gap-4 ${
                item.completed
                  ? 'border-slate-200 bg-slate-50/40 opacity-75'
                  : 'border-slate-200 hover:border-indigo-200 hover:shadow-sm'
              }`}
            >
              <div className="flex items-start gap-3.5">
                <input
                  type="checkbox"
                  checked={item.completed}
                  onChange={() => handleToggle(item.id)}
                  className="mt-1 h-5 w-5 rounded text-indigo-600 focus:ring-indigo-500 border-slate-300 cursor-pointer shrink-0"
                />
                <div className="flex flex-col gap-1 flex-1">
                  <div className="flex items-center justify-between gap-2 flex-wrap">
                    <span
                      className={`text-[10px] uppercase font-bold px-2 py-0.5 rounded tracking-wide ${
                        item.priority === 'high'
                          ? 'text-rose-700 bg-rose-50 border border-rose-200'
                          : item.priority === 'medium'
                          ? 'text-amber-700 bg-amber-50 border border-amber-200'
                          : 'text-slate-600 bg-slate-100 border border-slate-200'
                      }`}
                    >
                      {item.priorityLabel}
                    </span>
                    <span className="text-[11px] text-slate-400 font-medium">{item.targetTimeline}</span>
                  </div>

                  <h3 className={`text-sm font-bold ${item.completed ? 'line-through text-slate-400' : 'text-slate-900'}`}>
                    {item.title}
                  </h3>

                  <p className="text-xs text-slate-500 leading-relaxed">
                    {item.subtitle}
                  </p>
                </div>
              </div>

              <div className="flex items-center justify-between pt-3 border-t border-slate-100 text-xs">
                <span className="text-[11px] font-semibold text-slate-500 bg-slate-100 px-2 py-0.5 rounded">
                  {item.categoryTag} • {item.moduleRelated}
                </span>
                <span className="font-bold text-indigo-700 bg-indigo-50 px-2 py-0.5 rounded border border-indigo-100 text-[11px]">
                  {item.estimatedBoost}
                </span>
              </div>
            </div>
          ))}
        </div>

        {/* Study Plan Generator Tool */}
        <div className="bg-white rounded-2xl p-6 border border-slate-200 shadow-xs flex flex-col gap-4">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2">
            <div className="flex items-center gap-3">
              <div className="w-9 h-9 rounded-xl bg-indigo-50 text-indigo-600 flex items-center justify-center font-bold">
                <span className="material-symbols-outlined text-[20px]">calendar_today</span>
              </div>
              <div>
                <h3 className="text-base font-bold text-slate-900">Deliberate Study Time Optimizer</h3>
                <p className="text-xs text-slate-400">Generate an optimal weekly pacing schedule based on pending recommendations</p>
              </div>
            </div>

            <div className="flex items-center gap-3">
              <div className="flex items-center gap-1.5 text-xs text-slate-600 font-medium">
                <span>Available Hours/Day:</span>
                <input
                  type="number"
                  min="1"
                  max="8"
                  value={studyPlanHours}
                  onChange={(e) => setStudyPlanHours(Number(e.target.value))}
                  className="w-14 h-8 px-2 text-center rounded bg-slate-50 border border-slate-200 font-bold text-slate-900 font-mono"
                />
              </div>
              <button
                type="button"
                onClick={() => setGeneratedPlan(true)}
                className="px-4 py-2 bg-slate-900 text-white rounded-lg text-xs font-semibold hover:bg-slate-800 transition-colors"
              >
                Generate Schedule
              </button>
            </div>
          </div>

          {generatedPlan && (
            <div className="mt-2 p-4 rounded-xl bg-indigo-50/50 border border-indigo-100 text-xs text-slate-700 space-y-2">
              <div className="flex items-center justify-between font-bold text-indigo-900 pb-1 border-b border-indigo-100">
                <span>Recommended 7-Day Allocation ({studyPlanHours * 7} hours total):</span>
                <span className="text-[11px] bg-indigo-100 px-2 py-0.5 rounded">Optimized for +4.2% Boost</span>
              </div>
              <div className="grid grid-cols-1 sm:grid-cols-3 gap-3 pt-1">
                <div className="p-2.5 rounded-lg bg-white border border-indigo-100">
                  <div className="font-bold text-slate-900">Mon &amp; Wed (Maths IV Focus)</div>
                  <div className="text-slate-500 mt-1">2.0 hrs PDE problem sets + 1.5 hrs Python Lab DSA</div>
                </div>
                <div className="p-2.5 rounded-lg bg-white border border-indigo-100">
                  <div className="font-bold text-slate-900">Tue &amp; Thu (DBMS &amp; Web)</div>
                  <div className="text-slate-500 mt-1">2.0 hrs SQL Query tuning + 1.5 hrs React Full Stack</div>
                </div>
                <div className="p-2.5 rounded-lg bg-white border border-indigo-100">
                  <div className="font-bold text-slate-900">Fri &amp; Sat (Networks &amp; Mocks)</div>
                  <div className="text-slate-500 mt-1">2.0 hrs OSI/TCP quizzes + 2.0 hrs Mock Exam Recap</div>
                </div>
              </div>
            </div>
          )}
        </div>

      </div>
    </div>
  );
};
